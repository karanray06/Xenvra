export function getTemplateSpecById(id: string): TemplateSpec {
  const found = TEMPLATE_LIBRARY.find((t) => t.id === id);
  if (found) return found;
  // Fallback to modern-classic if id not found or legacy
  return TEMPLATE_LIBRARY[0];
}

export function filterTemplateSpecs(filters: {
  category?: string;
  industry?: string;
  tier?: string;
  atsSafeOnly?: boolean;
}): TemplateSpec[] {
  return TEMPLATE_LIBRARY.filter((t) => {
    if (filters.category && filters.category !== "all" && t.category !== filters.category) {
      return false;
    }
    if (filters.industry && filters.industry !== "all" && t.industry !== filters.industry) {
      return false;
    }
    if (filters.tier && filters.tier !== "all" && t.tier !== filters.tier) {
      return false;
    }
    if (filters.atsSafeOnly && !t.atsSafe) {
      return false;
    }
    return true;
  });
}
